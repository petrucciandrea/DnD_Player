-- Chat del party: messaggi a tutto il gruppo (destinatario NULL) o privati a un membro.
-- `tiro` contiene un tiro di dadi condiviso (tipo 'tiro'). Solo tabelle nuove.
CREATE TABLE party_messaggi (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  party_id integer NOT NULL REFERENCES party(id) ON DELETE CASCADE,
  autore_id integer NOT NULL REFERENCES utenti(id) ON DELETE CASCADE,
  destinatario_id integer REFERENCES utenti(id) ON DELETE CASCADE,
  tipo text NOT NULL DEFAULT 'testo' CHECK (tipo IN ('testo', 'tiro')),
  testo text NOT NULL DEFAULT '',
  tiro jsonb,
  creato timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX party_messaggi_party ON party_messaggi (party_id, id);

-- Fin dove l'utente ha letto ogni conversazione: con_utente_id 0 = chat di gruppo,
-- altrimenti i messaggi privati con quell'utente.
CREATE TABLE party_letture (
  party_id integer NOT NULL REFERENCES party(id) ON DELETE CASCADE,
  utente_id integer NOT NULL REFERENCES utenti(id) ON DELETE CASCADE,
  con_utente_id integer NOT NULL DEFAULT 0,
  ultimo bigint NOT NULL DEFAULT 0,
  PRIMARY KEY (party_id, utente_id, con_utente_id)
);
