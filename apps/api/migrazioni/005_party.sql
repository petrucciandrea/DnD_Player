-- Party: un gruppo di gioco con un Master e i giocatori, ognuno con un suo personaggio.
-- Si entra con il codice d'invito. Solo tabelle nuove: il codice precedente continua a funzionare durante il deploy.
CREATE TABLE party (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome text NOT NULL,
  codice text NOT NULL UNIQUE,       -- 8 caratteri senza trattino (XXXXXXXX), mostrato come XXXX-XXXX
  creato timestamptz NOT NULL DEFAULT now()
);

-- Il Master non ha un personaggio; ogni giocatore ne ha uno. Un personaggio sta in un solo party.
CREATE TABLE party_membri (
  party_id integer NOT NULL REFERENCES party(id) ON DELETE CASCADE,
  utente_id integer NOT NULL REFERENCES utenti(id) ON DELETE CASCADE,
  ruolo text NOT NULL CHECK (ruolo IN ('master', 'giocatore')),
  personaggio_id integer UNIQUE REFERENCES personaggi(id) ON DELETE CASCADE,
  entrato timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (party_id, utente_id),
  CHECK ((ruolo = 'master') = (personaggio_id IS NULL))
);
CREATE UNIQUE INDEX party_un_master ON party_membri (party_id) WHERE ruolo = 'master';
CREATE INDEX party_membri_utente ON party_membri (utente_id);
