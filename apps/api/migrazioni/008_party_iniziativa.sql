-- Combattimento del party: la riga esiste solo mentre uno scontro è in corso.
-- `di_turno` è la voce d'iniziativa di turno (NULL prima del primo turno). Solo tabelle nuove.
CREATE TABLE party_combattimento (
  party_id integer PRIMARY KEY REFERENCES party(id) ON DELETE CASCADE,
  round integer NOT NULL DEFAULT 1,
  di_turno integer,
  avviato timestamptz NOT NULL DEFAULT now()
);

-- Ordine d'iniziativa: i personaggi dei giocatori (personaggio_id) e i mostri o PNG del Master (personaggio_id NULL).
-- `bonus` (modificatore d'iniziativa) spareggia; `nascosto`: i giocatori non vedono la voce.
CREATE TABLE party_iniziativa (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  party_id integer NOT NULL REFERENCES party(id) ON DELETE CASCADE,
  personaggio_id integer REFERENCES personaggi(id) ON DELETE CASCADE,
  nome text NOT NULL,
  valore integer NOT NULL,
  bonus integer NOT NULL DEFAULT 0,
  nascosto boolean NOT NULL DEFAULT false,
  UNIQUE (party_id, personaggio_id)
);
CREATE INDEX party_iniziativa_party ON party_iniziativa (party_id);
