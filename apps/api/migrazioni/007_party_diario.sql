-- Diario di campagna del party: voci condivise (sessioni, PNG, luoghi, missioni) che tutti i membri
-- leggono e scrivono. Solo il Master fissa una voce in alto. `revisione` per le modifiche contemporanee.
CREATE TABLE party_diario (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  party_id integer NOT NULL REFERENCES party(id) ON DELETE CASCADE,
  titolo text NOT NULL,
  testo text NOT NULL DEFAULT '',
  categoria text NOT NULL DEFAULT 'altro' CHECK (categoria IN ('sessione', 'png', 'luogo', 'missione', 'altro')),
  fissata boolean NOT NULL DEFAULT false,
  autore_id integer REFERENCES utenti(id) ON DELETE SET NULL,
  aggiornato_da integer REFERENCES utenti(id) ON DELETE SET NULL,
  revisione integer NOT NULL DEFAULT 1,
  creato timestamptz NOT NULL DEFAULT now(),
  aggiornato timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX party_diario_party ON party_diario (party_id);
