-- Tesoro comune del party: monete e oggetti del gruppo, separati dall'inventario dei personaggi,
-- con lo storico di chi ha preso o messo cosa. Solo tabelle nuove.
CREATE TABLE party_monete (
  party_id integer PRIMARY KEY REFERENCES party(id) ON DELETE CASCADE,
  mr integer NOT NULL DEFAULT 0 CHECK (mr >= 0),
  ma integer NOT NULL DEFAULT 0 CHECK (ma >= 0),
  me integer NOT NULL DEFAULT 0 CHECK (me >= 0),
  mo integer NOT NULL DEFAULT 0 CHECK (mo >= 0),
  mp integer NOT NULL DEFAULT 0 CHECK (mp >= 0)
);

-- Stessi campi di un oggetto dello Zaino (personaggio_oggetti); peso in kg per unità.
CREATE TABLE party_oggetti (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  party_id integer NOT NULL REFERENCES party(id) ON DELETE CASCADE,
  nome text NOT NULL,
  qta integer NOT NULL CHECK (qta > 0),
  peso double precision NOT NULL DEFAULT 0,
  consumabile boolean NOT NULL DEFAULT false,
  consumo_giornaliero double precision NOT NULL DEFAULT 0,
  aggiornato timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX party_oggetti_party ON party_oggetti (party_id);

CREATE TABLE party_tesoro_movimenti (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  party_id integer NOT NULL REFERENCES party(id) ON DELETE CASCADE,
  utente_id integer REFERENCES utenti(id) ON DELETE SET NULL,
  descrizione text NOT NULL,
  creato timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX party_tesoro_movimenti_party ON party_tesoro_movimenti (party_id, id);
