-- Proposte del Master ai personaggi del party: PE da assegnare, un riposo breve o lungo, un giorno che passa.
-- Il server non tocca la scheda: il giocatore accetta (la sua scheda le applica) o rifiuta, e la proposta sparisce.
-- Chi esce dal party (o cancella il personaggio) perde le proposte in sospeso. Solo una tabella nuova.
CREATE TABLE party_proposte (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  party_id integer NOT NULL REFERENCES party(id) ON DELETE CASCADE,
  personaggio_id integer NOT NULL REFERENCES party_membri(personaggio_id) ON DELETE CASCADE,
  tipo text NOT NULL CHECK (tipo IN ('pe', 'riposo_breve', 'riposo_lungo', 'giorno')),
  pe integer CHECK (pe > 0),            -- solo per i PE: la quota di questo personaggio
  motivo text NOT NULL DEFAULT '',
  creato timestamptz NOT NULL DEFAULT now(),
  CHECK ((tipo = 'pe') = (pe IS NOT NULL))
);
CREATE INDEX party_proposte_personaggio ON party_proposte (personaggio_id);
CREATE INDEX party_proposte_party ON party_proposte (party_id);
